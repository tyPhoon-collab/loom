import { copyFile, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const playgroundDir = path.resolve(scriptDir, "..");
const configPath = path.join(playgroundDir, "sounds", "gm-lite-sources.json");
const outputDir = path.join(playgroundDir, "public", "sounds", "gm-lite");

const vcslRoot = path.resolve(process.argv[2] ?? process.env.VCSL_ROOT ?? "");

if (!process.argv[2] && !process.env.VCSL_ROOT) {
  fail("Usage: node apps/playground/scripts/build-gm-lite-sounds.mjs <VCSL_ROOT>");
}

await assertDirectory(vcslRoot, "VCSL root");

const config = JSON.parse(await readFile(configPath, "utf8"));
const manifest = {
  version: 1,
  instruments: {},
  drums: {},
};

await rm(path.join(outputDir, "instruments"), { recursive: true, force: true });
await rm(path.join(outputDir, "drums"), { recursive: true, force: true });
await rm(path.join(outputDir, ".DS_Store"), { force: true });
await mkdir(outputDir, { recursive: true });

const copiedRows = [];
await copyEntries("instruments", config.instruments);
await copyEntries("drums", config.drums);

await writeFile(path.join(outputDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(path.join(outputDir, "README.md"), renderReadme(config, copiedRows));
await writeFile(path.join(outputDir, "LICENSE"), renderLicense(config));

console.log(`Generated ${copiedRows.length} GM-lite samples in ${path.relative(process.cwd(), outputDir)}`);

async function copyEntries(section, entries) {
  for (const [key, entry] of Object.entries(entries)) {
    const sourceRelativePath = assertRelativePath(entry.source, `${section}.${key}.source`);
    const outputRelativePath = assertRelativePath(entry.output, `${section}.${key}.output`);
    const sourcePath = path.join(vcslRoot, sourceRelativePath);
    const outputPath = path.join(outputDir, outputRelativePath);

    await assertFile(sourcePath, `${section}.${key}`);
    await mkdir(path.dirname(outputPath), { recursive: true });
    await copyFile(sourcePath, outputPath);

    manifest[section][key] = manifestEntry(entry);
    copiedRows.push({
      output: outputRelativePath,
      source: sourceRelativePath,
    });
  }
}

function manifestEntry(entry) {
  const result = {
    path: entry.output,
    mode: entry.mode,
  };
  if (entry.rootNote !== undefined) {
    result.rootNote = entry.rootNote;
  }
  if (entry.loop !== undefined) {
    result.loop = entry.loop;
  }
  if (entry.gain !== undefined) {
    result.gain = entry.gain;
  }
  return result;
}

function renderReadme(config, rows) {
  const tableRows = rows
    .map((row) => `| \`${row.output}\` | \`${row.source.replaceAll("|", "\\|")}\` |`)
    .join("\n");

  return `# GM-lite Browser Preview Samples

These files are a small GM-lite preview set for Loom Playground. They are not a complete General MIDI sound set.

Generated by:

\`\`\`sh
just playground::gm-lite-sounds <VCSL_ROOT>
\`\`\`

Source material:

- ${config.source.name} ${config.source.version}
- Homepage: ${config.source.homepage}
- License: ${config.source.license}

Level policy:

- Samples are used at their source-library level by default.
- Manifest \`gain\` is an optional corrective trim for clearly problematic samples, not routine loudness normalization.

Bundled sample mapping:

| Output file | Source file |
| --- | --- |
${tableRows}
`;
}

function renderLicense(config) {
  return `${config.source.license}

The bundled GM-lite preview samples are copied from ${config.source.name} ${config.source.version}.
VCSL is distributed under Creative Commons 0.

Source homepage:

${config.source.homepage}

`;
}

function assertRelativePath(value, label) {
  if (typeof value !== "string" || value.length === 0) {
    fail(`${label} must be a non-empty string`);
  }
  if (path.isAbsolute(value) || value.split(/[\\/]/).includes("..")) {
    fail(`${label} must be a relative path inside its root: ${value}`);
  }
  return value;
}

async function assertDirectory(target, label) {
  try {
    const info = await stat(target);
    if (!info.isDirectory()) {
      fail(`${label} is not a directory: ${target}`);
    }
  } catch (error) {
    if (error?.code === "ENOENT") {
      fail(`${label} does not exist: ${target}`);
    }
    throw error;
  }
}

async function assertFile(target, label) {
  try {
    const info = await stat(target);
    if (!info.isFile()) {
      fail(`${label} is not a file: ${target}`);
    }
  } catch (error) {
    if (error?.code === "ENOENT") {
      fail(`${label} source file does not exist: ${target}`);
    }
    throw error;
  }
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
